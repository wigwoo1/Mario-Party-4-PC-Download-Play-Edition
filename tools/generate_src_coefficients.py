"""Generate Partyboard's CC0 windowed-sinc SRC replacement (not console ROM).

Three 128-phase, four-tap Q15 banks, in the SDK's existing bank/phase order.
This is an independent implementation of standard windowed-sinc filtering;
no Dolphin code, generated table, ROM bytes or GBA compatibility patches are
included. Dolphin's free-DSP documentation is useful background on why a
replacement polyphase table is possible, not an exactness claim:
https://github.com/dolphin-emu/dolphin/blob/master/docs/DSP/free_dsp_rom/dsp_rom_readme.txt

Use --check to reproduce the committed header without changing it. Tests
measure the quantized filters, independently of the runtime convolution.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import struct

NAME = "partyboard-windowed-sinc-q15-v1"
CUTOFFS = (0.5, 0.75, 1.0)  # Fractions of source Nyquist, in SDK bank order.
TARGET = Path(__file__).resolve().parents[1] / "src/port/src_coefficients.h"


def coefficients():
    banks = []
    for cutoff in CUTOFFS:
        phases = []
        for phase in range(128):
            # History is oldest first. The interpolation centre advances from
            # history[1] towards history[2], retaining the four-tap delay.
            distances = [tap - 1 - phase / 128 for tap in range(4)]
            weights = [
                (1 if x == 0 else math.sin(math.pi * cutoff * x) / (math.pi * cutoff * x))
                * (0.54 + 0.46 * math.cos(math.pi * x / 2))
                for x in distances
            ]
            gain = sum(weights)
            words = [max(-32768, min(32767, round(w / gain * 32767))) for w in weights]
            # Preserve DC after quantization and signed-word saturation. Near
            # integer phases the normalized central weight can slightly exceed
            # one, so distribute its small residual to the next nearest tap.
            remaining = 32767 - sum(words)
            for tap in sorted(range(4), key=lambda tap: abs(distances[tap])):
                correction = max(-32768 - words[tap], min(32767 - words[tap], remaining))
                words[tap] += correction
                remaining -= correction
            assert remaining == 0
            assert sum(words) == 32767 and all(-32768 <= w <= 32767 for w in words)
            phases.append(words)
        banks.append(phases)
    return banks


def response(words, frequency):
    real = sum(w * math.cos(math.pi * frequency * tap) for tap, w in enumerate(words))
    imag = sum(w * math.sin(math.pi * frequency * tap) for tap, w in enumerate(words))
    return math.hypot(real, imag) / 32767


def validate(banks):
    # Constant level, smooth phase progression, time-reversed phase symmetry,
    # and useful low-pass ordering. A four-tap table cannot eliminate aliases
    # at arbitrary pitch; no brick-wall/console-fidelity claim is made.
    metrics = []
    for index, phases in enumerate(banks):
        assert all(sum(p) == 32767 for p in phases)
        symmetry = max(abs(phases[p][t] - phases[128-p][3-t])
                       for p in range(1, 128) for t in range(4))
        adjacent = max(abs(phases[p+1][t] - phases[p][t])
                       for p in range(127) for t in range(4))
        low = [response(p, 0.05) for p in phases]
        high = [response(p, 1.0) for p in phases]
        assert symmetry <= 1 and adjacent < 500
        assert min(low) > 0.99 and max(low) < 1.001
        metrics.append(dict(bank=index, cutoff=CUTOFFS[index], dcSum=32767,
                            maxSymmetryError=symmetry, maxAdjacentStep=adjacent,
                            lowFrequencyGainRange=[min(low), max(low)],
                            nyquistGainRange=[min(high), max(high)]))
    assert banks[2][0] == [0, 32767, 0, 0]  # Exact integer-phase alignment.
    assert metrics[0]['nyquistGainRange'][1] < 0.45
    assert metrics[1]['nyquistGainRange'][1] < 0.7
    for phase in range(128):
        assert response(banks[0][phase], 0.8) < response(banks[1][phase], 0.8)
        assert response(banks[1][phase], 0.8) < response(banks[2][phase], 0.8)
    return metrics


def header(banks):
    flat = [v for bank in banks for phase in bank for v in phase]
    digest = hashlib.sha256(struct.pack('<1536h', *flat)).hexdigest()
    lines = ["/* Generated by tools/generate_src_coefficients.py; CC0-1.0.",
             " * Partyboard replacement, NOT original console ROM or a Dolphin table.",
             " * Four-tap Hamming-windowed sinc; cutoff .5/.75/1 source Nyquist.",
             " * Per-phase DC sum32767; oldest-first history, 128 phases per bank.",
             " * Little-endian signed-word SHA256: " + digest, " */",
             "#ifndef PARTYBOARD_SRC_COEFFICIENTS_H", "#define PARTYBOARD_SRC_COEFFICIENTS_H",
             "#include <stddef.h>", "#include <stdint.h>",
             '#define PARTYBOARD_SRC_COEFFICIENT_PROVIDER "' + NAME + '"',
             '#define PARTYBOARD_SRC_COEFFICIENT_SHA256 "' + digest + '"',
             "#define PARTYBOARD_SRC_COEFFICIENT_WORDS 1536u",
             "static const int16_t PartyboardSrcReplacementCoefficients[1536] = {"]
    for index, bank in enumerate(banks):
        lines.append("    /* SDK bank %d, cutoff %.2f */" % (index, CUTOFFS[index]))
        for phase in bank:
            lines.append("    " + ", ".join(str(v) for v in phase) + ",")
    lines += ["};", "/* Immutable lifetime; no file, heap or per-device calculation required.",
              " * Missing-bank rejection remains in the low-level runtime. Call this",
              " * provider explicitly when selecting the approved replacement default. */",
              "static inline const int16_t *PartyboardSrcDefaultCoefficients(size_t *words) {",
              "    if(words) *words = PARTYBOARD_SRC_COEFFICIENT_WORDS;",
              "    return PartyboardSrcReplacementCoefficients;", "}", "#endif", ""]
    return "\n".join(lines), digest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    banks = coefficients()
    metrics = validate(banks)
    rendered, digest = header(banks)
    if args.check:
        assert TARGET.read_text() == rendered, "Coefficient header differs; regenerate and review"
    else:
        TARGET.write_text(rendered, encoding='utf-8', newline='\n')
    report = dict(provider=NAME, status='VERIFIED coefficient design checks',
                  originalConsoleTable=False, copiedDolphinTable=False,
                  wordCount=1536, signedLittleEndianSha256=digest, banks=metrics,
                  limits='Replacement sound; four taps provide limited alias suppression. No listening or original-console comparison.')
    if args.report:
        args.report.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
