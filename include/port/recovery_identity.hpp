#pragma once
#include "crypto.hpp"
#include <nlohmann/json.hpp>
#include <array>
#include <mutex>
#include <regex>
#include <set>
#include <stdexcept>

namespace partyboard::net {
// Wire-compatible with web/recovery-identity.mjs. The caller must obtain this
// credential from the original authenticated connection, never a replacement.
class RecoveryIdentity {
    using Json = nlohmann::ordered_json;
    Json credential_;
    std::set<std::string> used_;
    std::mutex mutex_;
    static bool hex(const Json& value, size_t length) {
        if (!value.is_string()) return false;
        const auto& text = value.get_ref<const std::string&>();
        return text.size() == length && text.find_first_not_of("0123456789abcdef") == std::string::npos;
    }
    static unsigned digit(char value) { return value <= '9' ? value - '0' : value - 'a' + 10; }
    static std::array<unsigned char, 32> bytes(const std::string& text) {
        std::array<unsigned char, 32> result{};
        for (size_t i = 0; i < result.size(); ++i) result[i] = static_cast<unsigned char>(digit(text[2*i])*16 + digit(text[2*i+1]));
        return result;
    }
    Json canonical(const Json& message, const std::string& expectedType = "") const {
        const auto& description = message.at("description");
        const auto type = description.at("type").get<std::string>();
        const auto sdp = description.at("sdp").get<std::string>();
        // Validate UTF-8, then match JavaScript's UTF-16 code-unit limit.
        (void)Json(sdp).dump();
        size_t sdpUnits = 0;
        for (unsigned char byte : sdp) {
            if ((byte & 0xc0) != 0x80) sdpUnits += byte >= 0xf0 ? 2 : 1;
        }
        if (message.at("type") != "recovery-description" || message.at("version") != 1 ||
            message.at("session") != credential_.at("session") ||
            message.at("assetId") != credential_.at("assetId") ||
            message.at("peer") != credential_.at("peer") || !hex(message.at("nonce"), 32) ||
            (type != "offer" && type != "answer") || (!expectedType.empty() && type != expectedType) ||
            sdp.empty() || sdpUnits > 100000) throw std::invalid_argument("Invalid authenticated recovery description");
        return Json{{"type", "recovery-description"}, {"version", 1},
            {"session", message.at("session")}, {"assetId", message.at("assetId")},
            {"peer", message.at("peer")}, {"nonce", message.at("nonce")},
            {"description", Json{{"type", type}, {"sdp", sdp}}}};
    }
    std::array<unsigned char, 32> signature(const Json& packet) const {
        const auto secret = bytes(credential_.at("secret").get<std::string>());
        const auto text = packet.dump();
        return crypto::hmacSha256(secret, std::span<const uint8_t>(
            reinterpret_cast<const uint8_t*>(text.data()), text.size()));
    }
public:
    explicit RecoveryIdentity(const Json& credential) : credential_(credential) {
        if (credential.at("type") != "recovery-credential" || credential.at("version") != 1 ||
            !hex(credential.at("session"), 32) || !hex(credential.at("assetId"), 64) ||
            !hex(credential.at("secret"), 64) || credential.at("secret") == std::string(64, '0') ||
            !std::regex_match(credential.at("peer").get<std::string>(), std::regex("guest[1-9][0-9]{0,8}")))
            throw std::invalid_argument("Invalid recovery credential");
    }
    // Nonce must be generated by the caller's cryptographic random source.
    Json sign(const Json& description, const std::string& nonce) const {
        auto packet = canonical(Json{{"type", "recovery-description"}, {"version", 1},
            {"session", credential_.at("session")}, {"assetId", credential_.at("assetId")},
            {"peer", credential_.at("peer")}, {"nonce", nonce}, {"description", description}});
        const auto digest = signature(packet);
        static constexpr char digits[] = "0123456789abcdef";
        std::string encoded;
        for (auto byte : digest) { encoded += digits[byte >> 4]; encoded += digits[byte & 15]; }
        packet["signature"] = encoded;
        return packet;
    }
    bool verify(const Json& message, const std::string& type, const std::string& expectedNonce = "") {
        if (type != "offer" && type != "answer") throw std::invalid_argument("Expected recovery type required");
        const auto packet = canonical(message, type);
        const auto nonce = packet.at("nonce").get<std::string>();
        if (!message.contains("signature") || !hex(message.at("signature"), 64) ||
            (type == "answer" && nonce != expectedNonce)) return false;
        const auto supplied = bytes(message.at("signature").get<std::string>());
        const auto expected = signature(packet);
        unsigned difference = 0;
        for (size_t i = 0; i < expected.size(); ++i) difference |= supplied[i] ^ expected[i];
        if (difference) return false;
        std::lock_guard lock(mutex_);
        return used_.insert(type + ":" + nonce).second;
    }
};
}
